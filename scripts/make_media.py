#!/usr/bin/env python
"""Regenerate every figure under docs/media/ deterministically.

Each module already owns one or more figure-producing functions; this script's only job is to
call every one of them, from one place, with a fixed seed, so the pictures in the docs stay
reproducible from the code that made them. It computes nothing itself.

    .venv/bin/python scripts/make_media.py                    # every section except --all's extras
    .venv/bin/python scripts/make_media.py --only scene,demos  # just these sections
    .venv/bin/python scripts/make_media.py --all               # also the ~2200-episode press
                                                                 # baseline sweep (slow)
    .venv/bin/python scripts/make_media.py --strict            # non-zero exit if any section fails

Note on the default (no `--only`) run: the `envs` section's `brick_builder.envs.align_env.
make_align_figures` measures success against 20 episodes per point across noise, age and both
perception producers -- several minutes on its own, independent of `--all` (which only gates the
separate, heavier press-misalignment sweep). Pass `--only` to skip it for a quick run.

A section that raises is reported and skipped rather than aborting the whole run, since sections
are independent and each one's own tests already cover it; `--strict` turns that into a non-zero
exit code, for a caller (the test suite, CI) that wants to know none of a chosen subset failed.

Every section writes under `--out-root` (default: the repo root, i.e. the real `docs/media/`
tree every docs page links to). The test suite passes a temporary `--out-root` instead, so
running these tests never touches the checked-in figures under `docs/media/`: each subdirectory
there is generated by its own module, listed in `SECTIONS` below (this script's own output is
`docs/media/demos/**` only).
"""

from __future__ import annotations

import argparse
import os
import traceback
from pathlib import Path

os.environ.setdefault("CUDA_VISIBLE_DEVICES", "")
os.environ.setdefault("MUJOCO_GL", "egl")

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]


# --------------------------------------------------------------------------------------- scene ---


def _scene(seed: int, run_all: bool, out_root: Path) -> None:
    del run_all, seed  # make_scene_figures has no seed parameter; the default scene is deterministic
    from brick_builder.scene.compose import make_scene_figures

    make_scene_figures(out_dir=str(out_root / "docs/media/scene"))


def _bricks(seed: int, run_all: bool, out_root: Path) -> None:
    del seed, run_all
    from brick_builder.bricks import media as bricks_media

    out_dir = out_root / "docs/media/bricks"
    out_dir.mkdir(parents=True, exist_ok=True)  # unlike most figure functions, these don't mkdir themselves
    bricks_media.make_exploded_collision_vs_visual_figure(out_path=str(out_dir / "exploded_collision_vs_visual.png"))
    bricks_media.make_force_vs_depth_figure(out_path=str(out_dir / "force_vs_depth.png"))
    bricks_media.make_rocking_vs_flat_figure(out_path=str(out_dir / "rocking_vs_flat.png"))


def _robot(seed: int, run_all: bool, out_root: Path) -> None:
    del seed, run_all
    from brick_builder.robot import force_map, servo_model

    out_dir = out_root / "docs/media/robot"
    force_map.make_figures(out_dir=out_dir)
    servo_model.make_figures(out_dir=out_dir)


def _control(seed: int, run_all: bool, out_root: Path) -> None:
    del run_all
    from brick_builder.control.primitives import make_control_figures
    from brick_builder.control.skill_fsm import make_verify_figure

    out_dir = str(out_root / "docs/media/control")
    make_control_figures(out_dir=out_dir, seed=seed)
    make_verify_figure(out_dir=out_dir, seed=seed)


def _envs(seed: int, run_all: bool, out_root: Path) -> None:
    from brick_builder.envs.align_env import make_align_figures
    from brick_builder.envs.press_env import make_press_figures

    out_dir = str(out_root / "docs/media/envs")
    make_align_figures(out_dir=out_dir)
    if run_all:
        make_press_figures(out_dir=out_dir, seed=seed)  # measures a fresh ~2200-episode sweep
        return
    cached = REPO_ROOT / "runs" / "press_baseline" / "curve.json"
    if cached.exists():
        make_press_figures(out_dir=out_dir, results=str(cached), seed=seed)
    else:
        print("  (press_baseline_curve.png: no cached sweep at runs/press_baseline/curve.json "
              "and --all not given; pass --all to measure one)")


def _render(seed: int, run_all: bool, out_root: Path) -> None:
    del run_all
    from brick_builder.render.domain_rand import PostProcessConfig, plot_postprocess_before_after
    from brick_builder.render.renderer import SceneRenderer, plot_contact_sheet
    from brick_builder.scene.compose import OVERVIEW_CAM, SceneConfig, build_scene, reset_scene

    out_dir = out_root / "docs/media/render"
    scene = build_scene(SceneConfig(cameras=(OVERVIEW_CAM,)))
    reset_scene(scene, np.random.default_rng(seed))
    renderer = SceneRenderer(scene.model, width=480, height=360)
    try:
        frame = renderer.render(scene.data, OVERVIEW_CAM)
        plot_contact_sheet(frame, out_dir / "contact_sheet.png")
        plot_postprocess_before_after(
            frame, PostProcessConfig(), np.random.default_rng(seed), out_dir / "postprocess_before_after.png",
        )
    finally:
        renderer.close()


def _rl(seed: int, run_all: bool, out_root: Path) -> None:
    del seed, run_all
    from brick_builder.rl.ppo_asym import plot_learning_curve

    # The RL core's own acceptance figure (a throwaway Pendulum-v1 task, not a BrickBuilder skill) is
    # tied to a specific slow test run and is not regenerated here; see
    # tests/rl/test_ppo_asym.py::test_learns_pendulum and docs/guide/05-training-and-evaluation.md.
    # A real BrickBuilder run's own curve is instead written straight into its run directory by
    # scripts/train.py (<run_dir>/learning_curve.png), from the same function.
    reach = REPO_ROOT / "runs" / "reach_smoke" / "returns.json"
    if not reach.exists():
        print("  (skipping: no runs/reach_smoke/returns.json)")
        return
    import json

    history = json.loads(reach.read_text())
    out_path = out_root / "docs/media/envs/reach_learning_curve.png"
    plot_learning_curve(history, out_path, title="Reach learning curve")


def _export(seed: int, run_all: bool, out_root: Path) -> None:
    del run_all
    ckpt = REPO_ROOT / "runs" / "reach_smoke" / "checkpoint.pt"
    if not ckpt.exists():
        print("  (skipping parity_and_speed.png: no runs/reach_smoke/checkpoint.pt)")
        return
    from brick_builder.export.build import build_library
    from brick_builder.export.c_policy import CPolicy
    from brick_builder.export.parity import plot_parity_and_speed
    from brick_builder.rl.ppo_asym import load_actor

    _, _, obs_spec = load_actor(ckpt)
    build_dir = out_root / "brick_builder_export_build"  # never brick_builder/export/_build: that dir is
    # this repo's real (git-ignored) build output, and a test's --out-root run should not touch it
    lib_float, _ = build_library(ckpt, build_dir=build_dir, tanh_table=False)
    lib_table, _ = build_library(ckpt, build_dir=build_dir, tanh_table=True)
    cp_float = CPolicy(lib_float, obs_spec["actor_dim"], obs_spec["act_dim"])
    cp_table = CPolicy(lib_table, obs_spec["actor_dim"], obs_spec["act_dim"])
    plot_parity_and_speed(
        ckpt, cp_float, cp_table, out_root / "docs/media/export/parity_and_speed.png",
        n_parity=2000, n_calls=500,
    )
    _ = seed


def _eval(seed: int, run_all: bool, out_root: Path) -> None:
    del run_all
    from brick_builder.eval.report import plot_success_heatmap
    from brick_builder.eval.results import EpisodeResult

    # A synthetic success surface: no trained policy involved, just a made-up shape to show what
    # the figure looks like (see docs/demos/README.md). Real sweep heatmaps come from
    # scripts/eval.py --sweep press-misalign once a checkpoint exists.
    rng = np.random.default_rng(seed)
    results: list[EpisodeResult] = []
    for lat_mm in (0, 2, 4, 6, 8):
        for yaw_deg in (0, 4, 8, 12):
            p = float(np.clip(1.0 - 0.09 * lat_mm - 0.05 * yaw_deg, 0.02, 0.98))
            n = 40
            successes = int(rng.binomial(n, p))
            for i in range(n):
                results.append(EpisodeResult(
                    success=i < successes, steps=50,
                    params={"lateral_mm": lat_mm, "yaw_deg": yaw_deg},
                ))
    plot_success_heatmap(
        results, "lateral_mm", "yaw_deg", out_root / "docs/media/eval/example_heatmap.png",
        x_label="lateral misalignment (mm)", y_label="yaw misalignment (deg)",
        title="Synthetic example success surface (no trained policy)",
    )


def _demos(seed: int, run_all: bool, out_root: Path) -> None:
    """Regenerate the demo gallery. Unlike every other section, `docs/media/demos/**` is this
    package's own path, so when `out_root` is the repo root (the default, real run) this writes
    the same files `python -m brick_builder.demo <name>` would; under a test's temporary `out_root` it
    is redirected via each demo's own `record=` argument instead of a shared `out_dir` convention.
    """
    del run_all
    import importlib

    from brick_builder.demo import DEMOS

    out_dir = out_root / "docs/media/demos"
    extensions = {"scene": "png", "force-map": "png"}
    for name, module_name in DEMOS.items():
        record = str(out_dir / f"{name.replace('-', '_')}.{extensions.get(name, 'mp4')}")
        try:
            module = importlib.import_module(module_name)
            module.run(record=record, seed=seed, extra=())
        except Exception as exc:  # noqa: BLE001 -- report and keep going; see run() below
            print(f"  ({name} demo failed: {exc})")


SECTIONS: dict[str, callable] = {
    "scene": _scene,
    "bricks": _bricks,
    "robot": _robot,
    "control": _control,
    "envs": _envs,
    "render": _render,
    "rl": _rl,
    "export": _export,
    "eval": _eval,
    "demos": _demos,
}


def run(only: list[str] | None, seed: int, run_all: bool, out_root: Path) -> dict[str, str]:
    names = only if only else list(SECTIONS)
    status: dict[str, str] = {}
    for name in names:
        if name not in SECTIONS:
            raise ValueError(f"unknown section {name!r}; choose from {sorted(SECTIONS)}")
        print(f"== {name} ==")
        try:
            SECTIONS[name](seed, run_all, out_root)
            status[name] = "ok"
        except Exception:
            traceback.print_exc()
            status[name] = "failed"
    return status


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", default=None, help="comma-separated section names")
    parser.add_argument("--all", action="store_true", help="include the slow extras (the press sweep)")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--strict", action="store_true", help="exit 1 if any selected section failed")
    parser.add_argument("--out-root", type=Path, default=REPO_ROOT,
                         help="write under <out-root>/docs/media/... instead of the repo's own "
                         "docs/media/ (the test suite uses this; leave it out for a real run)")
    args = parser.parse_args(argv)

    only = [s.strip() for s in args.only.split(",")] if args.only else None
    status = run(only, args.seed, args.all, args.out_root)

    print("\n== summary ==")
    for name, result in status.items():
        print(f"{name:<12} {result}")

    if args.strict and any(v == "failed" for v in status.values()):
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
