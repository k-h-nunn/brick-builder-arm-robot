"""Turn the two closed-loop action models into plain C data, and check the two agree.

`write_header` reads the learned inverse and the next-scene-state predictor
(`brick_builder/action/weights/*.npz`, written by `scripts/train_action_model.py`) and emits
`action_theta.h`: both networks' weight matrices and biases, their frozen input normalizers'
mean and standard deviation, their output scales, and the macros `c/action_net.c` needs to size
its buffers. `build_library` compiles that against the hand-written `c/action_net.c`, and
`check_parity` compares the compiled `action_inverse` / `action_predict` against the NumPy
forward pass of `brick_builder.action.models.mlp.Mlp` on logged inputs.

The same pattern as the actor export (`actor_to_c.py`), and deliberately a separate file: the
container here is an `.npz` of two small MLPs with their own normalizers, not a learner's
checkpoint, and both networks go into one header so the firmware links one translation unit.

    python -m brick_builder.export.action_to_c --out brick_builder/export/_build
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

import numpy as np

from brick_builder.action.models.mlp import Mlp

C_DIR = Path(__file__).resolve().parent / "c"
DEFAULT_BUILD_DIR = Path(__file__).resolve().parent / "_build"
WEIGHTS = Path(__file__).resolve().parents[1] / "action" / "weights"


def _c_float(v: float) -> str:
    s = f"{float(np.float32(v)):.9g}"
    if not any(ch in s for ch in ".eEnN"):
        s += ".0"
    return s + "f"


def _wrapped(values: Sequence[str], per_line: int = 8, indent: str = "    ") -> list[str]:
    out = []
    for i in range(0, len(values), per_line):
        out.append(indent + ", ".join(values[i:i + per_line]) + ",")
    if out:
        out[-1] = out[-1][:-1]
    return out


def _array(name: str, values: np.ndarray) -> list[str]:
    flat = np.asarray(values, dtype=np.float32).reshape(-1)
    return ([f"static const float {name}[{flat.size}] = {{"]
            + _wrapped([_c_float(v) for v in flat]) + ["};"])


def _emit(prefix: str, macro: str, net: Mlp) -> list[str]:
    sizes = net.sizes
    lines = [
        f"/* {macro}: {' -> '.join(str(s) for s in sizes)}, "
        f"{net.n_params} parameters, {net.macs} MAC, {net.weight_bytes} bytes */",
        f"#define {macro}_IN_DIM {sizes[0]}",
        f"#define {macro}_OUT_DIM {sizes[-1]}",
        f"#define {macro}_N_LAYERS {len(net.layers)}",
        f"#define {macro}_CLIP {_c_float(net.clip)}",
        "",
    ]
    for i, (w, b) in enumerate(net.layers):
        lines += _array(f"{prefix}_w{i}", w) + _array(f"{prefix}_b{i}", b) + [""]
    lines.append(f"static const int {prefix}_layer_in[{macro}_N_LAYERS] = {{"
                 + ", ".join(str(w.shape[1]) for w, _ in net.layers) + "};")
    lines.append(f"static const int {prefix}_layer_out[{macro}_N_LAYERS] = {{"
                 + ", ".join(str(w.shape[0]) for w, _ in net.layers) + "};")
    lines.append(f"static const float *const {prefix}_weights[{macro}_N_LAYERS] = {{"
                 + ", ".join(f"{prefix}_w{i}" for i in range(len(net.layers))) + "};")
    lines.append(f"static const float *const {prefix}_biases[{macro}_N_LAYERS] = {{"
                 + ", ".join(f"{prefix}_b{i}" for i in range(len(net.layers))) + "};")
    lines.append("")
    lines += _array(f"{prefix}_norm_mean", net.in_mean)
    lines += _array(f"{prefix}_norm_std", net.in_std)
    lines += _array(f"{prefix}_out_mean", net.out_mean)
    lines += _array(f"{prefix}_out_std", net.out_std)
    lines.append("")
    return lines


def write_header(inverse: Path, predictor: Path, out_dir: Path) -> Path:
    """Write `<out_dir>/action_theta.h` from the two checkpoints. Returns its path."""
    g = Mlp.load(inverse)
    f = Mlp.load(predictor)
    width = max(max(g.sizes), max(f.sizes))
    lines = [
        "/* action_theta.h: GENERATED by brick_builder/export/action_to_c.py. DO NOT EDIT BY HAND.",
        " *",
        " * The closed loop's two learned models as plain C data: weight matrices and biases",
        " * (row-major, out x in, matching torch.nn.Linear.weight), each network's frozen input",
        " * normalizer (mean and standard deviation, divided rather than multiplied so the C and",
        " * the NumPy reference agree bit for bit), and each network's output scale.",
        " *",
        f" * inverse       {inverse.name}  sha256 {hashlib.sha256(inverse.read_bytes()).hexdigest()[:16]}",
        f" * predictor     {predictor.name}  sha256 {hashlib.sha256(predictor.read_bytes()).hexdigest()[:16]}",
        f" * inverse       {' -> '.join(str(s) for s in g.sizes)}  "
        f"{g.macs} MAC  {g.weight_bytes} bytes",
        f" * predictor     {' -> '.join(str(s) for s in f.sizes)}  "
        f"{f.macs} MAC  {f.weight_bytes} bytes",
        " */",
        "#ifndef ACTION_THETA_H",
        "#define ACTION_THETA_H",
        "",
        f"#define ACTION_MAX_WIDTH {width}",
        "",
    ]
    lines += _emit("action_inv", "ACTION_INV", g)
    lines += _emit("action_pred", "ACTION_PRED", f)
    lines.append("#endif /* ACTION_THETA_H */")

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "action_theta.h"
    path.write_text("\n".join(lines) + "\n")
    return path


def build_library(inverse: Path = None, predictor: Path = None,
                  build_dir: Path = DEFAULT_BUILD_DIR, *, tanh_table: bool = False,
                  cc: str = "gcc") -> tuple[Path, Path]:
    """Generate the header and compile `c/action_net.c` against it.

    Same flags as the actor export: `-O2 -std=c99 -ffp-contract=off`, so no fused multiply-add
    contraction changes the rounding the NumPy reference does.
    """
    inverse = Path(inverse) if inverse is not None else WEIGHTS / "inverse.npz"
    predictor = Path(predictor) if predictor is not None else WEIGHTS / "predictor.npz"
    build_dir = Path(build_dir)
    build_dir.mkdir(parents=True, exist_ok=True)
    header = write_header(inverse, predictor, build_dir)
    if tanh_table:
        from brick_builder.export.actor_to_c import write_tanh_table

        write_tanh_table(build_dir)

    lib = build_dir / ("action_table.so" if tanh_table else "action_float.so")
    cmd = [cc, "-O2", "-std=c99", "-ffp-contract=off", "-shared", "-fPIC", "-Wall", "-Wextra",
           "-I", str(C_DIR), "-I", str(build_dir)]
    if tanh_table:
        cmd.append("-DACTION_TANH_TABLE")
    cmd += [str(C_DIR / "action_net.c"), "-o", str(lib)]
    if not tanh_table:
        cmd.append("-lm")
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"gcc failed (exit {result.returncode}) on: {' '.join(cmd)}\n"
                           f"--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}")
    return lib, header


@dataclass
class ParityReport:
    n: int
    inverse_max_abs_error: float
    predictor_max_abs_error: float

    def ok(self, bound: float = 1e-6) -> bool:
        return max(self.inverse_max_abs_error, self.predictor_max_abs_error) <= bound


def check_parity(lib: Path, inverse: Path, predictor: Path, x_inv: np.ndarray,
                 x_pred: np.ndarray) -> ParityReport:
    """Compare the compiled forward pass against the NumPy one on logged inputs."""
    from brick_builder.export.c_action import CActionNet

    g, f = Mlp.load(inverse), Mlp.load(predictor)
    net = CActionNet(lib, g.sizes[0], g.sizes[-1], f.sizes[0], f.sizes[-1])
    e_inv = np.abs(net.inverse_batch(x_inv) - g.forward(x_inv))
    e_pred = np.abs(net.predict_batch(x_pred) - f.forward(x_pred))
    return ParityReport(n=int(min(len(x_inv), len(x_pred))),
                        inverse_max_abs_error=float(e_inv.max()),
                        predictor_max_abs_error=float(e_pred.max()))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="action_to_c", description=__doc__.split("\n\n")[0])
    parser.add_argument("--inverse", default=str(WEIGHTS / "inverse.npz"))
    parser.add_argument("--predictor", default=str(WEIGHTS / "predictor.npz"))
    parser.add_argument("--out", default=str(DEFAULT_BUILD_DIR))
    parser.add_argument("--data", nargs="+", default=["data_cache/action/placement"])
    parser.add_argument("--n", type=int, default=1000)
    args = parser.parse_args(argv)

    lib, header = build_library(Path(args.inverse), Path(args.predictor), Path(args.out))
    print(f"{header}\n{lib}")

    from brick_builder.action.learn import dataset as ds

    data = ds.load(args.data, limit=8)
    teach = ds.teacher_pairs(data)
    pred = ds.predictor_pairs(data)
    n = min(args.n, len(teach["x"]), len(pred["x"]))
    report = check_parity(lib, Path(args.inverse), Path(args.predictor),
                          teach["x"][:n], pred["x"][:n])
    print(f"parity on {report.n} logged inputs: inverse {report.inverse_max_abs_error:.3e}, "
          f"predictor {report.predictor_max_abs_error:.3e}")
    return 0 if report.ok() else 1


if __name__ == "__main__":
    raise SystemExit(main())
